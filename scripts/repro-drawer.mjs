// Diagnostic only — not part of the extension, not part of the build.
//
//   node scripts/repro-drawer.mjs            # headless
//   node scripts/repro-drawer.mjs --headed   # watch it
//
// Reproduces the studio SHAPE locally and runs the real pipeline against it,
// so the mechanism is demonstrated rather than argued. No studio access, no
// login, no extension — the pipeline scripts come straight out of src via
// scripts/probe-reveal.mjs, which is the same instrument being handed to Adam.
//
// The shape being reproduced, from the studio evidence:
//   - the document itself does not scroll (docBarelyScrolls -> true)
//   - a dominant inner scroller holds the content (the Notion shape, so
//     detectInnerScroll selects InnerScrollExpansionStrategy)
//   - a drawer that is closed on screen
//
// Five variants, each closed a different way, so the run says WHICH closing
// techniques the pipeline defeats rather than just "a drawer leaked":
//
//   A off-canvas-left100  position:absolute; left:100%, clipped by an ancestor
//   B off-canvas-transform right:0 + transform:translateX(100%), same clip
//   C display-none        control: must never appear
//   D visibility-hidden   the FORCE_REVEAL case
//   E lazy-content        control: SHOULD be revealed; if this stops painting
//                         a fix has over-corrected
//
// Every variant also carries aria-hidden="true" on the drawer so the run
// reports whether the ruled signals would even have been reachable.

import { spawn, execFileSync } from 'node:child_process';
import { createServer } from 'node:http';
import { existsSync, rmSync } from 'node:fs';
import { DRAWER_VARIANTS, fixture, viewportFor } from './drawer-fixture.mjs';

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const CHROME =
  process.env.CHROME_BIN ??
  `${process.env.HOME}/.cache/puppeteer/chrome/mac_arm-151.0.7922.77/chrome-mac-arm64/` +
    'Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing';
const PORT = 9336;
const HTTP_PORT = 8767;
const HEADED = process.argv.includes('--headed');
// One browser, one window size, so a run covers variants that share a
// viewport. S uses studio's literal offsets and therefore studio's viewport;
// running it alongside A-E at 1440 would put the drawer back on canvas and the
// fixture would silently stop reproducing anything.
const ONLY = process.argv.find((a) => a.startsWith('--variant='))?.slice(10) ?? null;
const VARIANTS = ONLY ? [ONLY] : Object.keys(DRAWER_VARIANTS).filter((v) => !v.startsWith('S '));
const VIEWPORT = viewportFor(VARIANTS[0]);

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// The probe is generated by the same script Adam pastes, so this reproduction
// and his console run are the identical instrument.
const PROBE = execFileSync('node', [`${ROOT}/scripts/probe-reveal.mjs`], {
  encoding: 'utf8',
  maxBuffer: 4 << 20,
});

class Session {
  constructor(url) {
    this.url = url;
    this.id = 0;
    this.pending = new Map();
  }
  async open() {
    this.ws = new WebSocket(this.url);
    await new Promise((resolve, reject) => {
      this.ws.onopen = resolve;
      this.ws.onerror = reject;
    });
    this.ws.onmessage = (event) => {
      const msg = JSON.parse(event.data);
      const entry = this.pending.get(msg.id);
      if (!entry) return;
      this.pending.delete(msg.id);
      msg.error ? entry.reject(new Error(JSON.stringify(msg.error))) : entry.resolve(msg.result);
    };
  }
  send(method, params = {}) {
    const id = ++this.id;
    this.ws.send(JSON.stringify({ id, method, params }));
    return new Promise((resolve, reject) => this.pending.set(id, { resolve, reject }));
  }
  async eval(expression) {
    const r = await this.send('Runtime.evaluate', {
      expression,
      awaitPromise: true,
      returnByValue: true,
    });
    if (r.exceptionDetails) throw new Error(r.exceptionDetails.exception?.description ?? 'eval threw');
    return r.result.value;
  }
  close() {
    try {
      this.ws.close();
    } catch {
      /* already gone */
    }
  }
}

// Rejects rather than returns while the browser is still starting up, so the
// readiness loop below has to tolerate a throw, not just a falsy value.
const cdp = async (path, method = 'GET') => {
  const res = await fetch(`http://127.0.0.1:${PORT}${path}`, { method });
  const text = await res.text();
  try {
    return JSON.parse(text);
  } catch {
    return text;
  }
};

function serve() {
  const server = createServer((req, res) => {
    const url = new URL(req.url, `http://127.0.0.1:${HTTP_PORT}`);
    const variant = url.searchParams.get('v') ?? 'A off-canvas-left100';
    res.writeHead(200, { 'content-type': 'text/html; charset=utf-8' });
    res.end(fixture(variant));
  });
  server.listen(HTTP_PORT, '127.0.0.1');
  return server;
}

if (!existsSync(CHROME)) {
  console.error(`Chrome for Testing not found at:\n  ${CHROME}\nSet CHROME_BIN.`);
  process.exit(1);
}

// A persisted profile remembers its window size, which silently overrides
// --window-size and puts S's drawer back on canvas. Measured: the doc came
// back 1440 wide on a run that asked for 1300.
rmSync('/tmp/ck-repro-profile', { recursive: true, force: true });

const server = serve();
const chrome = spawn(
  CHROME,
  [
    `--remote-debugging-port=${PORT}`,
    '--user-data-dir=/tmp/ck-repro-profile',
    `--window-size=${VIEWPORT.width},${VIEWPORT.height}`,
    '--no-first-run',
    '--no-default-browser-check',
    ...(HEADED ? [] : ['--headless=new']),
    'about:blank',
  ],
  { stdio: 'ignore' },
);

const cleanup = () => {
  try {
    chrome.kill();
  } catch {}
  try {
    server.close();
  } catch {}
};
const cleanupAndExit = (code) => {
  cleanup();
  process.exit(code);
};
process.on('exit', cleanup);
process.on('SIGINT', () => cleanupAndExit(130));

// Wait for the browser to answer.
let ready = false;
for (let i = 0; i < 40 && !ready; i++) {
  try {
    const v = await cdp('/json/version');
    ready = Boolean(v && v.webSocketDebuggerUrl);
  } catch {
    /* port not listening yet */
  }
  if (!ready) await sleep(250);
}
if (!ready) {
  console.error(`Chrome never opened a debugging port on ${PORT}.`);
  cleanupAndExit(1);
}

const results = {};
for (const variant of VARIANTS) {
  const pageUrl = `http://127.0.0.1:${HTTP_PORT}/?v=${encodeURIComponent(variant)}`;
  // /json/new is PUT-only on this Chrome, and it does not reliably return the
  // target, so the tab is found by URL off /json/list afterwards.
  await cdp(`/json/new?${encodeURIComponent(pageUrl)}`, 'PUT');
  await sleep(1200);
  const target = (await cdp('/json/list')).find((t) => t.url === pageUrl);
  if (!target) {
    results[variant] = { error: 'tab never appeared' };
    continue;
  }
  const session = new Session(target.webSocketDebuggerUrl);
  await session.open();
  await session.send('Runtime.enable');
  await sleep(600);
  try {
    results[variant] = await session.eval(PROBE);
  } catch (error) {
    results[variant] = { error: String(error.message ?? error) };
  }
  session.close();
  await cdp(`/json/close/${target.id}`);
}

// ---- report -------------------------------------------------------------
const line = (s) => console.log(s);
line(`\nviewport ${VIEWPORT.width}x${VIEWPORT.height}, chrome ${CHROME.split('/').pop()}\n`);

for (const [variant, out] of Object.entries(results)) {
  line('='.repeat(72));
  line(variant);
  line('='.repeat(72));
  if (out.error) {
    line(`  ERROR: ${out.error}`);
    continue;
  }
  line(`  innerScrollStrategySelected: ${out.innerScrollStrategySelected}`);
  line(`  forceRevealCount:            ${out.forceRevealCount}`);
  line(`  unstickTargets:              ${out.unstickTargets}`);
  line('  document box by stage:');
  for (const s of out.docBoxByStage) line(`    ${s}`);
  line('  tracked elements:');
  for (const f of out.firstPaint) {
    line(`    ${f.el}`);
    line(`      paintedAtBaseline: ${f.paintedAtBaseline}   becomesPaintedAt: ${f.becomesPaintedAt}`);
    line(`      ${f.sequence}`);
  }
  // The decisive row: what the drawer looked like before, and at the stage it
  // started painting.
  const idx = out.firstPaint.findIndex((f) => f.el.includes('drawer'));
  if (idx >= 0) {
    const first = out.stages[0].tracked[idx];
    const stageName = out.firstPaint[idx].becomesPaintedAt;
    const at = out.stages.find((s) => s.stage === stageName)?.tracked[idx];
    line('  drawer detail:');
    line(`    S0  painted=${first.painted} docRect=${first.docRect} paintedArea=${first.paintedArea}`);
    line(`        position=${first.position} transform=${first.transform} inset=${first.inset}`);
    line(`        closedMarker=${first.closedMarker}  forceRevealMarked=${first.forceRevealMarked}`);
    line(`        clippers=${JSON.stringify(first.clippers)}`);
    if (at) {
      line(`    ${stageName}  painted=${at.painted} docRect=${at.docRect} paintedArea=${at.paintedArea}`);
      line(`        expandAttr=${at.expandAttr} unstickKind=${at.unstickKind} forceRevealMarked=${at.forceRevealMarked}`);
      line(`        clippers=${JSON.stringify(at.clippers)}`);
    }
  }
  line('');
}

line('='.repeat(72));
line('VERDICTS');
line('='.repeat(72));
for (const [variant, out] of Object.entries(results)) {
  if (out.error) {
    line(`  ${variant.padEnd(24)} ERROR`);
    continue;
  }
  const drawer = out.firstPaint.find((f) => f.el.includes('drawer'));
  const lazy = out.firstPaint.find((f) => f.el.includes('lazy'));
  if (variant.startsWith('E')) {
    line(`  ${variant.padEnd(24)} lazy block becomesPaintedAt=${lazy?.becomesPaintedAt ?? 'not tracked'}`);
    continue;
  }
  const leaked = drawer && drawer.becomesPaintedAt !== 'never' && !drawer.paintedAtBaseline;
  line(
    `  ${variant.padEnd(24)} ${
      leaked
        ? `LEAKS — closed on screen, paints from ${drawer.becomesPaintedAt}`
        : drawer?.paintedAtBaseline
          ? 'inconclusive — drawer already painted at baseline (fixture wrong)'
          : 'stays closed'
    }`,
  );
}
line('');

cleanup();
